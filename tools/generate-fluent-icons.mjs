const symbols = await Promise.all(names.map(async name => {
  const source = await readFile(new URL(`../icons/fluent/${name}-20-regular.svg`, import.meta.url), 'utf8');
  const body = source.match(/<svg\b[^>]*>([\s\S]*?)<\/svg>/)?.[1];
  if (!body) throw new Error(`Invalid SVG: ${name}`);
  // The supplied SVG wrappers use 100x100, but these paths use 20x20 coordinates.
  return `  <symbol id="${name}" viewBox="0 0 20 20">${body}</symbol>`;
}));
await writeFile(new URL('../icons/ui.svg', import.meta.url), `<!-- Generated by tools/generate-fluent-icons.mjs. Fluent UI System Icons, MIT; see fluent-LICENSE. -->
<svg xmlns="http://www.w3.org/2000/svg">
${symbols.join('\n')}
</svg>
`);
